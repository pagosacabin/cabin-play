/*
 * 0243 -- SD-card slideshow on the living frame (N16R8, MAC c4:9e:7e:08:6d:f4).
 *
 * One project, two apps, selected by build flag:
 *
 *   APP_STAGE=1  (env n16r8-slideshow-stage) -- copies the ten framebuffer
 *                rasters staged in the `frames` flash partition onto the card
 *                at /sdcard/FRAMES, then proves each file byte-for-byte by
 *                reading it back and comparing SHA-256 with the flash copy.
 *                The card is identity-gated first: nothing is written unless
 *                the seated card is 0241's SanDisk (CID PSN 0xc6bd0f92).
 *
 *   APP_STAGE=0  (env n16r8-slideshow) -- the slideshow itself: mounts the
 *                card with the 0239 fold (raw pre-sacrifice + one stock
 *                driver init), enumerates /sdcard/FRAMES sorted by name,
 *                streams each raster into the VGA framebuffer and advances
 *                every ~10 s, looping to the first frame after the last.
 *                No card / no valid frames -> the embedded hummingbird is
 *                displayed exactly as the accepted 0228 build does.
 *
 * Driver, pins, timings and the 800x600 mode are the accepted build's
 * (n16r8-photo, env n16r8-photo-800x600): 1 framebuffer byte = 1 DAC byte =
 * 1 output pixel, 8 bpp RGB222, 15-line bounce buffers, no_fb streaming.
 *
 * The FT232R console on this bench delivers nothing (0225), so every claim in
 * the report partition is written by this app and read back with esptool.
 * Only this app's own lines go in the report -- the IDF log is left to the
 * console so 0241's lesson (DEBUG/VERBOSE flooding the report buffer) cannot
 * recur.
 */
