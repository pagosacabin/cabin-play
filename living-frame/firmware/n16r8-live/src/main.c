/*
 * 0227 -- a real photograph on the 64-colour build (living frame, N16R8).
 *
 * Same driver as 0226 (0180's LCD_CAM RGB path, native 640x480, 8 bpp RGB222,
 * framebuffer in PSRAM, 16-line bounce buffers, nothing doubled), with the test
 * card replaced by one dithered photograph that is embedded in the app image.
 *
 * Orientation: the photograph is rotated 90 deg COUNTER-clockwise by the host
 * converter, i.e. flipped 180 deg relative to 0226's test card, because
 * Stephen's monitor is pivoted the other way (task 0227 amendment, 2026-11-20).
 * Nothing is rotated or resampled on the device: the framebuffer is a straight
 * 307,200-byte blit, so 1 fb pixel = 1 DAC byte = 1 output pixel.
 *
 * Verification: the app hashes the framebuffer it actually streams and compares
 * that against the SHA-256 the converter wrote into photo64_meta.h.  That makes
 * "the panel is showing the converted photograph" a checkable claim rather than
 * a hope -- the only thing left for a human is whether it looks good.
 */
#include <stdio.h>
#include <stdarg.h>
#include <string.h>
#include <stdlib.h>

#include "freertos/FreeRTOS.h"
#include "freertos/task.h"
#include "esp_heap_caps.h"
#include "esp_lcd_panel_rgb.h"
#include "esp_lcd_panel_ops.h"
