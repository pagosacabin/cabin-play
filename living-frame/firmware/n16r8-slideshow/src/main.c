/* ---- report sink ---------------------------------------------------------
 * The report partition is the log, but the panel streams from PSRAM through a
 * bounce ISR, and a flash erase (64 KiB, tens of ms) stalls the cache that ISR
 * reads PSRAM through -- the RGB FIFO underflows.  So the whole partition is
 * erased ONCE at boot, before the panel starts, and every later persist is a
 * single 4 KiB sector write with no erase (a few ms, inside the bounce
 * budget).  Each persist is a record: magic, length, text.  The reader walks
 * the sectors in order and prints the text of every valid record.
 * ------------------------------------------------------------------------- */
#define REPORT_SECTOR   4096
#define REPORT_SECTORS  16
#define REPORT_MAGIC    0x30323433u   /* "0243" */

static char  g_report[60000];
static size_t g_report_len;
static const esp_partition_t *s_report_part;
static int s_report_sector;

static void app_logf(const char *fmt, ...)
{
    char line[400];
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(line, sizeof(line), fmt, ap);
    va_end(ap);
    if (n < 0) return;
    fputs(line, stdout);
    if (n > (int)sizeof(line) - 1) n = (int)sizeof(line) - 1;
    if (g_report_len + (size_t)n < sizeof(g_report)) {
        memcpy(g_report + g_report_len, line, (size_t)n);
        g_report_len += (size_t)n;
    }
}

/* Open the log.  The partition is erased only when it does not already hold
 * 0243 records: an earlier boot's log (e.g. the stage run before this show run)
 * is kept and this run appends after it.  Called before the panel starts, so an
 * erase is safe here and only here. */
static void report_open(void)
{
    s_report_part = esp_partition_find_first(ESP_PARTITION_TYPE_DATA,
                                             (esp_partition_subtype_t)0x40, "report");
    s_report_sector = 0;
    if (s_report_part == NULL) return;

    uint32_t hdr[2] = {0, 0};
    if (esp_partition_read(s_report_part, 0, hdr, sizeof hdr) == ESP_OK &&
        hdr[0] == REPORT_MAGIC && hdr[1] > 0 && hdr[1] <= REPORT_SECTOR - 8) {
        while (s_report_sector < REPORT_SECTORS) {
            size_t addr = (size_t)s_report_sector * REPORT_SECTOR;
            if (esp_partition_read(s_report_part, addr, hdr, sizeof hdr) != ESP_OK) break;
            if (hdr[0] != REPORT_MAGIC || hdr[1] == 0 || hdr[1] > REPORT_SECTOR - 8) break;
            s_report_sector++;
        }
        app_logf("REPORT: continuing the existing log at sector %d\n", s_report_sector);
        return;
    }
    esp_partition_erase_range(s_report_part, 0, s_report_part->size);
}

/* Persist everything logged since the last flush, in 4 KiB records.  No erase. */
static void report_flush(void)
{
    if (s_report_part == NULL || g_report_len == 0) return;
    size_t off = 0;
    while (off < g_report_len && s_report_sector < REPORT_SECTORS) {
        size_t chunk = g_report_len - off;
        if (chunk > REPORT_SECTOR - 8) chunk = REPORT_SECTOR - 8;
        uint32_t hdr[2] = { REPORT_MAGIC, (uint32_t)chunk };
        size_t addr = (size_t)s_report_sector * REPORT_SECTOR;
        if (esp_partition_write(s_report_part, addr, hdr, sizeof hdr) != ESP_OK ||
            esp_partition_write(s_report_part, addr + sizeof hdr, g_report + off, chunk) != ESP_OK) {
            return;   /* a failed persist must not take the display down */
        }
        s_report_sector++;
        off += chunk;
    }
    if (off >= g_report_len) {
        g_report_len = 0;
    } else if (off > 0) {
        memmove(g_report, g_report + off, g_report_len - off);
        g_report_len -= off;
    }
    /* Out of sectors: keep logging in RAM; the earlier records still stand. */
}

/* ---- SHA-256 ------------------------------------------------------------
 * Software implementation, carried over verbatim from 0241: mbedtls' digest
 * came back with its first 8 bytes zeroed inside that build's card-I/O path,
 * and the digests here are the evidence, so the hash is computed by code whose
 * two known answers are checked at boot before any digest is quoted. */
typedef struct {
    uint32_t h[8];
    uint64_t total;
    uint8_t  blk[64];
    size_t   fill;
} sw_sha256_t;

static const uint32_t S256_K[64] = {
    0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1,
    0x923f82a4, 0xab1c5ed5, 0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3,
    0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174, 0xe49b69c1, 0xefbe4786,
    0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
    0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147,
    0x06ca6351, 0x14292967, 0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13,
    0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85, 0xa2bfe8a1, 0xa81a664b,
    0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
    0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a,
    0x5b9cca4f, 0x682e6ff3, 0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208,
    0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2
};

static uint32_t s256_rotr(uint32_t x, int n) { return (x >> n) | (x << (32 - n)); }

static void s256_block(sw_sha256_t *s, const uint8_t *p)
{
    uint32_t w[64];
    for (int i = 0; i < 16; i++) {
        w[i] = ((uint32_t)p[i * 4] << 24) | ((uint32_t)p[i * 4 + 1] << 16) |
               ((uint32_t)p[i * 4 + 2] << 8) | (uint32_t)p[i * 4 + 3];
    }
    for (int i = 16; i < 64; i++) {
        uint32_t s0 = s256_rotr(w[i - 15], 7) ^ s256_rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = s256_rotr(w[i - 2], 17) ^ s256_rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }
    uint32_t a = s->h[0], b = s->h[1], c = s->h[2], d = s->h[3];
    uint32_t e = s->h[4], f = s->h[5], g = s->h[6], hh = s->h[7];
    for (int i = 0; i < 64; i++) {
        uint32_t S1 = s256_rotr(e, 6) ^ s256_rotr(e, 11) ^ s256_rotr(e, 25);
        uint32_t ch = (e & f) ^ ((~e) & g);
        uint32_t t1 = hh + S1 + ch + S256_K[i] + w[i];
        uint32_t S0 = s256_rotr(a, 2) ^ s256_rotr(a, 13) ^ s256_rotr(a, 22);
        uint32_t mj = (a & b) ^ (a & c) ^ (b & c);
        uint32_t t2 = S0 + mj;
        hh = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }
    s->h[0] += a; s->h[1] += b; s->h[2] += c; s->h[3] += d;
    s->h[4] += e; s->h[5] += f; s->h[6] += g; s->h[7] += hh;
}

static void s256_init(sw_sha256_t *s)
{
    s->h[0] = 0x6a09e667; s->h[1] = 0xbb67ae85; s->h[2] = 0x3c6ef372; s->h[3] = 0xa54ff53a;
    s->h[4] = 0x510e527f; s->h[5] = 0x9b05688c; s->h[6] = 0x1f83d9ab; s->h[7] = 0x5be0cd19;
    s->total = 0; s->fill = 0;
}

static void s256_update(sw_sha256_t *s, const uint8_t *p, size_t n)
{
    s->total += n;
    while (n--) {
        s->blk[s->fill++] = *p++;
        if (s->fill == 64) { s256_block(s, s->blk); s->fill = 0; }
    }
}

static void s256_final(sw_sha256_t *s, uint8_t out[32])
{
    uint64_t bits = s->total * 8ull;
    uint8_t pad = 0x80;
    s256_update(s, &pad, 1);
    uint8_t z = 0;
    while (s->fill != 56) s256_update(s, &z, 1);
    uint8_t len[8];
    for (int i = 0; i < 8; i++) len[i] = (uint8_t)(bits >> (56 - 8 * i));
    s256_update(s, len, 8);
    for (int i = 0; i < 8; i++) {
        out[i * 4]     = (uint8_t)(s->h[i] >> 24);
        out[i * 4 + 1] = (uint8_t)(s->h[i] >> 16);
        out[i * 4 + 2] = (uint8_t)(s->h[i] >> 8);
        out[i * 4 + 3] = (uint8_t)(s->h[i]);
    }
}

static void sha256_hex(sw_sha256_t *s, char out[65])
{
    uint8_t d[32];
    s256_final(s, d);
    for (int i = 0; i < 32; i++) snprintf(out + i * 2, 3, "%02x", d[i]);
    out[64] = 0;
}

static void sha256_buf(const uint8_t *p, size_t n, char out[65])
{
    sw_sha256_t s;
    s256_init(&s);
    s256_update(&s, p, n);
    sha256_hex(&s, out);
}

/* Checked before any digest is quoted: "abc" and 480,000 zero bytes. */
static bool sha_kat(void)
{
    char h[65];
    sha256_buf((const uint8_t *)"abc", 3, h);
    if (strcmp(h, "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad") != 0) {
        app_logf("SHA_KAT: FAIL on \"abc\": %s\n", h);
        return false;
    }
    /* 1 MiB of zeros in 4 KiB updates: a whole number of blocks, so the
     * expected digest cannot be off by a partial chunk. */
    static uint8_t z[4096];
    sw_sha256_t s;
    s256_init(&s);
    for (int i = 0; i < 256; i++) s256_update(&s, z, sizeof z);
    sha256_hex(&s, h);
    if (strcmp(h, "30e14955ebf1352266dc2ff8067e68104607e750abb9d3b36582b8af909fcb58") != 0) {
        app_logf("SHA_KAT: FAIL on 1 MiB of zeros: %s\n", h);
        return false;
    }
    app_logf("SHA_KAT: abc ok; 1 MiB of zeros ok\n");
    return true;
}

/* ---- SD: raw pre-sacrifice (0239) --------------------------------------- */
static const char *g_cmd_tag = "";
static bool g_raw_tx_err;

static uint8_t sd_crc7(const uint8_t *d, int n)
{
    uint8_t crc = 0;
    for (int k = 0; k < n; k++) {
        uint8_t b = d[k];
        for (int i = 0; i < 8; i++) {
            crc = (uint8_t)(crc << 1);
            if ((b & 0x80) ^ (crc & 0x80)) crc ^= 0x09;
            b = (uint8_t)(b << 1);
        }
    }
    return (uint8_t)((crc << 1) | 1);
}

static uint8_t sd_raw_cmd(spi_device_handle_t dev, uint8_t cmd, uint32_t arg,
                          int extra, uint8_t *out, int out_max)
{
    uint8_t tx[32], rx[32];
    memset(tx, 0xFF, sizeof tx);
    memset(rx, 0x00, sizeof rx);
    g_raw_tx_err = false;

    tx[0] = 0x40 | cmd;
    tx[1] = (uint8_t)(arg >> 24);
    tx[2] = (uint8_t)(arg >> 16);
    tx[3] = (uint8_t)(arg >> 8);
    tx[4] = (uint8_t)(arg);
    tx[5] = sd_crc7(tx, 5);

    int n = 6 + 8 + extra;
    if (n > (int)sizeof(tx)) n = (int)sizeof(tx);

    gpio_set_level(PIN_CS, 0);
    spi_transaction_t t = {0};
    t.length = (size_t)n * 8;
    t.tx_buffer = tx;
    t.rx_buffer = rx;
    esp_err_t err = spi_device_transmit(dev, &t);
    gpio_set_level(PIN_CS, 1);

    {
        uint8_t ff = 0xFF;
        spi_transaction_t tail = {0};
        tail.length = 8;
        tail.tx_buffer = &ff;
        if (spi_device_transmit(dev, &tail) != ESP_OK) g_raw_tx_err = true;
    }

    if (err != ESP_OK) {
        app_logf("    %sCMD%-2u: spi transfer failed (%s)\n", g_cmd_tag, cmd,
                 esp_err_to_name(err));
        g_raw_tx_err = true;
        return 0xFF;
    }

    int idx = -1;
    for (int i = 6; i < n; i++) {
        if ((rx[i] & 0x80) == 0) { idx = i; break; }
    }
    if (idx < 0) {
        app_logf("    %sCMD%-2u arg=0x%08" PRIx32 ": NO RESPONSE\n", g_cmd_tag, cmd, arg);
        return 0xFF;
    }
    int copied = 0;
    for (int i = idx + 1; i < n && copied < out_max && copied < extra; i++, copied++) {
        out[copied] = rx[i];
    }
    return rx[idx];
}

/* 74+ clocks with CS high, one throwaway CMD0, CS high, bus released so the
 * stock driver can initialise SPI2 itself.  Value and intent are 0239's; the
 * call is not skipped on a failed transfer (a failed frame is not a sacrifice). */
static esp_err_t fold_presacrifice(uint8_t *r1_out)
{
    *r1_out = 0xFF;
    app_logf("\n--- 0239 PRE-SACRIFICE (raw bus, before the driver) ---\n");

    spi_bus_config_t bus = {
        .mosi_io_num = PIN_MOSI,
        .miso_io_num = PIN_MISO,
        .sclk_io_num = PIN_SCK,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = 4096,
    };
    esp_err_t err = spi_bus_initialize(SPI2_HOST, &bus, SPI_DMA_CH_AUTO);
    if (err != ESP_OK) {
        app_logf("  SACRIFICE: spi_bus_initialize failed (%s) -- not counted\n",
                 esp_err_to_name(err));
        return err;
    }

    gpio_set_direction(PIN_CS, GPIO_MODE_OUTPUT);
    gpio_set_level(PIN_CS, 1);

    spi_device_interface_config_t devcfg = {0};
    devcfg.clock_speed_hz = 400 * 1000;
    devcfg.mode = 0;
    devcfg.spics_io_num = -1;
    devcfg.queue_size = 1;
    spi_device_handle_t dev = NULL;
    err = spi_bus_add_device(SPI2_HOST, &devcfg, &dev);
    if (err != ESP_OK) {
        app_logf("  SACRIFICE: add_device failed (%s) -- not counted\n", esp_err_to_name(err));
        spi_bus_free(SPI2_HOST);
        return err;
    }

    {
        uint8_t ff[10];
        memset(ff, 0xFF, sizeof ff);
        gpio_set_level(PIN_CS, 1);
        spi_transaction_t t = {0};
        t.length = sizeof(ff) * 8;
        t.tx_buffer = ff;
        err = spi_device_transmit(dev, &t);
    }
    if (err != ESP_OK) {
        app_logf("  SACRIFICE: dummy-clock transfer failed (%s) -- not counted\n",
                 esp_err_to_name(err));
        spi_bus_remove_device(dev);
        spi_bus_free(SPI2_HOST);
        return err;
    }

    uint8_t pl[8] = {0};
    g_cmd_tag = "SACRIFICE ";
    uint8_t r1 = sd_raw_cmd(dev, 0, 0x00000000, sizeof pl, pl, sizeof pl);
    g_cmd_tag = "";
    if (g_raw_tx_err) {
        app_logf("  SACRIFICE: CMD0 transfer failed -- not counted\n");
        gpio_set_level(PIN_CS, 1);
        spi_bus_remove_device(dev);
        spi_bus_free(SPI2_HOST);
        return ESP_FAIL;
    }
    gpio_set_level(PIN_CS, 1);
    spi_bus_remove_device(dev);
    spi_bus_free(SPI2_HOST);
    app_logf("  SACRIFICE: R1=0x%02x (discarded); bus released\n", r1);
    *r1_out = r1;
    return ESP_OK;
}

/* Mount with the stock driver at 400 kHz -- the clock, CS handling and
 * pull-ups are unchanged from the configuration 0241 proved. */
static bool card_mount(const char *tag, sdmmc_card_t **out)
{
    app_logf("\n--- SD MOUNT [%s] ---\n", tag);
    spi_bus_config_t bus = {
        .mosi_io_num = PIN_MOSI,
        .miso_io_num = PIN_MISO,
        .sclk_io_num = PIN_SCK,
        .quadwp_io_num = -1,
        .quadhd_io_num = -1,
        .max_transfer_sz = 4096,
    };
    esp_err_t err = spi_bus_initialize(SPI2_HOST, &bus, SPI_DMA_CH_AUTO);
    if (err != ESP_OK) {
        app_logf("  MOUNT_FAIL spi_bus_initialize=%s\n", esp_err_to_name(err));
        return false;
    }
    sdspi_device_config_t slot = SDSPI_DEVICE_CONFIG_DEFAULT();
    slot.host_id = SPI2_HOST;
    slot.gpio_cs = PIN_CS;

    sdmmc_host_t host = SDSPI_HOST_DEFAULT();
    host.slot = SPI2_HOST;
    host.max_freq_khz = 400;

    esp_vfs_fat_mount_config_t mcfg = {
        .format_if_mount_failed = false,
        .max_files = 4,
        .allocation_unit_size = 0,
    };
    sdmmc_card_t *card = NULL;
    err = esp_vfs_fat_sdspi_mount(SD_MOUNT_POINT, &host, &slot, &mcfg, &card);
    if (err != ESP_OK) {
        app_logf("  MOUNT_FAIL[%s]: %s (%d)\n", tag, esp_err_to_name(err), (int)err);
        spi_bus_free(SPI2_HOST);
        return false;
    }
    app_logf("  MOUNT_OK[%s]: card=%.*s psn=0x%08" PRIx32 " speed=%" PRIu32
             " kHz size=%llu MB\n",
             tag, 8, card->cid.name, (uint32_t)card->cid.serial, card->real_freq_khz,
             (unsigned long long)((uint64_t)card->csd.capacity * card->csd.sector_size
                                  / (1024 * 1024)));
    *out = card;
    return true;
}

static void card_unmount(sdmmc_card_t *card)
{
    esp_err_t err = esp_vfs_fat_sdcard_unmount(SD_MOUNT_POINT, card);
    app_logf("  UNMOUNT: %s\n", err == ESP_OK ? "ok" : esp_err_to_name(err));
    spi_bus_free(SPI2_HOST);
}

